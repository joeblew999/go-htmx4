// Command coregen writes kit/i18n's locale table (kit/i18n/cldr) from this module's full CLDR tables: only what
// the server still needs (locale ids, names, direction, plural rules, the digits and grouping of numbers in
// messages), since the browser formats everything else with its own Intl.
//
//	cd kit/i18n/legacy && go run ./cmd/coregen -out ../cldr/data_cldr.go
//
// `mise run i18n:generate` runs it after regenerating this module's tables for I18N_LOCALES.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"

	"github.com/joeblew999/go-htmx4/kit/i18n/legacy"
	"github.com/joeblew999/go-htmx4/kit/i18n/legacy/cldr"
)

func main() {
	out := flag.String("out", "../cldr/data_cldr.go", "output file")
	golden := flag.String("golden", "../testdata/numbers.json", "number formatting cases for kit/i18n's tests")
	flag.Parse()
	d := cldr.Data

	var b bytes.Buffer
	b.WriteString("// Code generated by kit/i18n/legacy/cmd/coregen from CLDR. DO NOT EDIT.\n\n")
	b.WriteString("// Package cldr is the app's shipped locales (kit/i18n's schema): ids, names, direction, plural rules and\n")
	b.WriteString("// the digits and grouping of numbers in messages. Regenerate with `mise run i18n:generate`.\n")
	b.WriteString("package cldr\n\nimport \"github.com/joeblew999/go-htmx4/kit/i18n\"\n\n")
	b.WriteString("// Data is the shipped locales, the default first.\n")
	fmt.Fprintf(&b, "var Data = &i18n.Data{\n\tCLDRVersion: %q,\n\tCLDRJSONVersion: %q,\n\tLocales: []*i18n.LocaleData{\n", d.CLDRVersion, d.CLDRJSONVersion)
	for _, ld := range d.Locales {
		parent := ""
		for id := d.Parent(ld.ID); id != "root" && parent == ""; id = d.Parent(id) {
			for _, other := range d.Locales {
				if other.ID == id {
					parent = id
				}
			}
		}
		sys := ld.Numbers.Systems[0] // the default system comes first
		if sys.ID != ld.Numbers.DefaultSystem {
			log.Fatalf("coregen: %s: first numbering system %s isn't the default %s", ld.ID, sys.ID, ld.Numbers.DefaultSystem)
		}
		region := i18n.MustParseTag(ld.Maximal).Region
		fmt.Fprintf(&b, "\t\t{\n\t\t\tID: %q, Maximal: %q, Parent: %q, RTL: %v, NativeName: %q, Currency: %q,\n",
			ld.ID, ld.Maximal, parent, ld.RTL, ld.NativeName, d.RegionCurrencyCode(region))
		fmt.Fprintf(&b, "\t\t\tCardinal: %s,\n\t\t\tOrdinal: %s,\n", rules(ld.Cardinal), rules(ld.Ordinal))
		fmt.Fprintf(&b, "\t\t\tNumbers: i18n.NumbersData{DefaultSystem: %q, NativeSystem: %q, Digits: %q, Decimal: %q, Group: %q, Minus: %q, Group1: %d, Group2: %d, MinGrouping: %d},\n\t\t},\n",
			ld.Numbers.DefaultSystem, ld.Numbers.NativeSystem, sys.Digits, sys.Symbols.Decimal, sys.Symbols.Group, sys.Symbols.Minus,
			sys.Decimal.Group1, sys.Decimal.Group2, ld.Numbers.MinGrouping)
	}
	b.WriteString("\t},\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("coregen: gofmt: %v\n%s", err, b.Bytes())
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("✓ %s: %d locales (CLDR %s)\n", *out, len(d.Locales), d.CLDRVersion)
	writeGolden(*golden, d)
}

// numberCases are the inputs kit/i18n's FormatNumber is checked on, against this module's Intl-conformant
// formatter (default options: at most 3 fraction digits; and maximumFractionDigits 0).
var numberCases = []string{"0", "-0", "7", "-42", "999", "1000", "1234", "12345", "123456", "1234567", "-1234567.891",
	"0.5", "2.5", "-2.5", "0.12345", "1.0005", "99999.9999", "1234567890123", "1e21"}

// writeGolden records what the full formatter outputs for numberCases in every shipped locale.
func writeGolden(path string, d *i18n.Data) {
	type row struct {
		Locale, Input string
		MaxFrac       int
		Want          string
	}
	var rows []row
	for _, ld := range d.Locales {
		loc := d.MustLocale(ld.ID)
		for _, maxFrac := range []int{3, 0} {
			f := loc.MustNumberFormat(i18n.NumberOptions{MaximumFractionDigits: i18n.N(maxFrac)})
			for _, in := range numberCases {
				rows = append(rows, row{ld.ID, in, maxFrac, f.FormatString(in)})
			}
		}
	}
	data, err := json.Marshal(rows)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		log.Fatal(err)
	}
	data = bytes.ReplaceAll(data, []byte("},{"), []byte("},\n{"))
	if err := os.WriteFile(path, append(data, '\n'), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("✓ %s: %d cases\n", path, len(rows))
}

// rules writes plural rules as a kit/i18n literal (the same shape in both packages).
func rules(r i18n.PluralRules) string {
	var b bytes.Buffer
	b.WriteString("i18n.PluralRules{")
	for _, rule := range r {
		fmt.Fprintf(&b, "{Cat: %d, Or: []i18n.AndCond{", rule.Cat)
		for _, and := range rule.Or {
			b.WriteString("{")
			for _, rel := range and {
				fmt.Fprintf(&b, "{Operand: %q, Mod: %d, Not: %v, Ranges: %#v},", rel.Operand, rel.Mod, rel.Not, rel.Ranges)
			}
			b.WriteString("},")
		}
		b.WriteString("}},")
	}
	b.WriteString("}")
	return b.String()
}
