// ImportPath is the intl package, which the generated code imports.
const ImportPath = "github.com/joeblew999/go-htmx4/intl"

// PseudoCatalog is the en-XA catalog: the source, pseudo-localized (accented, bracketed, ~40% longer).
const PseudoCatalog = "en-XA"

// Generate is go tool intl gen: it writes what package intl needs beside the catalogs, and intl.sum:
//
//	intl-messages.mjs         every catalog as data for js/intl.mjs's message, which formats it with Intl
//	intl_gen.go               an intl.Msg per key (so a missing key is a compile error): a value for a message
//	                          without arguments, a constructor for one with; the shipped locales, and their
//	                          registration with intl
//	<gsxui>/i18n/intl_gen.go  with intl.toml's gsxui: the renderer for the text gsxui components write themselves
//
// A file that would not change is left alone. log gets a line per locale.
func (p *Project) Generate(log io.Writer) error {
	if log == nil {
		log = io.Discard
	}
	dir := p.Config.CatalogDir()
	// A language just added to intl.toml gets its catalog, for whoever translates it to fill.
	for _, l := range p.Locales[1:] {
		if _, err := os.Stat(l.File); errors.Is(err, os.ErrNotExist) {
			head := "# " + l.ID + ": the translations of " + p.Locales[0].ID + ".toml, same tables and keys. go tool intl todo lists what is left.\n"
			if err := os.WriteFile(l.File, []byte(head), 0o644); err != nil {
				return err
			}
			fmt.Fprintf(log, "wrote %s\n", l.File)
		}
	}
	catalogs := map[string][]any{}
	var ids []string
	for _, l := range p.Locales {
		var out []any
		for i, e := range l.Entries {
			out = append(out, jsMessage(e.parsed.parts, p.Messages[i]))
		}
		catalogs[l.ID] = out
		ids = append(ids, l.ID)
		fmt.Fprintln(log, l.Summary(len(p.Messages)))
	}
	var pseudo []any
	for _, m := range p.Messages {
		pseudo = append(pseudo, jsMessage(pseudoNodes(m.parsed.parts, true), m))
	}
	catalogs[PseudoCatalog] = pseudo

	name := filepath.Base(dir)
	if err := writeJS(filepath.Join(dir, "intl-messages.mjs"), name, append(ids, PseudoCatalog), catalogs); err != nil {
		return err
	}

	var b strings.Builder
	b.WriteString("// Code generated by go tool intl gen from " + name + "/*.toml (intl.toml). DO NOT EDIT.\n\npackage " + name + "\n\n")
	b.WriteString("import \"" + ImportPath + "\"\n\n")
	b.WriteString("// Shipped are the app's locales (intl.toml), the source first.\nvar Shipped = intl.Locales{")
	for _, l := range p.Locales {
		fmt.Fprintf(&b, "intl.NewLocale(%q), ", l.ID)
	}
	b.WriteString("}\n\nfunc init() { intl.Use(Shipped, []bool{")
	for _, l := range p.Locales {
		fmt.Fprintf(&b, "%v, ", l.Complete())
	}
	b.WriteString("}) }\n\n")
	names := map[string]string{}
	for i, m := range p.Messages {
		fn := GoName(m.Key)
		if prev, dup := names[fn]; dup {
			return fmt.Errorf("intl: keys %s and %s both become %s", prev, m.Key, fn)
		}
		names[fn] = m.Key
		// Each argument has its own type parameter: a number argument takes any Go number (len(items)), a text
		// argument a string, a Msg or a Value (another message, an Intl result), made text when the message renders.
		var tparams, params, args []string
		for k, a := range m.parsed.order {
			pn, tp := paramName(a), fmt.Sprintf("T%d", k)
			if m.parsed.args[a] == argNumber {
				tparams = append(tparams, tp+" intl.NumberArg")
				args = append(args, "intl.Num("+pn+")")
			} else {
				tparams = append(tparams, tp+" intl.TextArg")
				args = append(args, "intl.Str("+pn+")")
			}
			params = append(params, pn+" "+tp)
		}
		doc := fmt.Sprintf("// %s is %q: %s\n", fn, m.Key, strings.ReplaceAll(m.Text, "\n", " "))
		if len(params) == 0 {
			// A message without arguments is a value, as gsx's Translation keys pattern writes it: { locales.NavHome }.
			fmt.Fprintf(&b, "%svar %s = intl.M(%d)\n\n", doc, fn, i)
			continue
		}
		fmt.Fprintf(&b, "%sfunc %s[%s](%s) intl.Msg { return intl.M(%d%s) }\n\n", doc, fn, strings.Join(tparams, ", "), strings.Join(params, ", "), i, prefixComma(args))
	}
	if err := writeGo(filepath.Join(dir, "intl_gen.go"), b.String()); err != nil {
		return err
	}
	if err := p.WriteSum(); err != nil {
		return err
	}
	if p.Config.Gsxui == "" {
		return nil
	}
	return p.writeGsxui()
}

// Summary is l's line in go tool intl gen and status: "de       160/167 translated, 3 stale, 4 missing".
func (l *Locale) Summary(total int) string {
	s := fmt.Sprintf("%-8s %d/%d translated", l.ID, total-l.Count(Missing)-l.Count(Stale), total)
	for _, st := range []State{Inherited, Stale, Missing} {
		if n := l.Count(st); n > 0 {
			s += fmt.Sprintf(", %d %s", n, st)
		}
	}
	return s
}

// jsMessage encodes a message for js/intl.mjs's message: a string when it is all text, else its parts (see
// message there), arguments by their index in the source message.
func jsMessage(nodes []node, m *Message) any {
	switch {
	case len(nodes) == 0:
		return ""
	case len(nodes) == 1 && nodes[0].kind == kText:
		return nodes[0].text
	}
	return jsParts(nodes, m)
}

func jsParts(nodes []node, m *Message) []any {
	out := make([]any, 0, len(nodes))
	for _, n := range nodes {
		i := m.index[n.arg]
		switch n.kind {
		case kText:
			out = append(out, n.text)
		case kArg:
			if m.parsed.args[n.arg] == argNumber {
				out = append(out, []any{"n", i, ""})
			} else {
				out = append(out, []any{"a", i})
			}
		case kNumber:
			out = append(out, []any{"n", i, n.style})
		case kPound:
			out = append(out, []any{"#"})
		case kPlural, kSelectOrdinal:
			tag := "p"
			if n.kind == kSelectOrdinal {
				tag = "o"
			}
			out = append(out, []any{tag, i, n.offset, jsCases(n.cases, m)})
		case kSelect:
			out = append(out, []any{"s", i, jsCases(n.cases, m)})
		}
	}
	return out
}

func jsCases(cases []caseNode, m *Message) map[string][]any {
	out := make(map[string][]any, len(cases))
	for _, c := range cases {
		out[c.key] = jsParts(c.parts, m)
	}
	return out
}

// writeJS writes the catalogs as one ES module whose default export is JSON, a message per line so a change reads
// as a diff.
func writeJS(path, dir string, ids []string, catalogs map[string][]any) error {
	var b strings.Builder
	b.WriteString("// Code generated by go tool intl gen from " + dir + "/*.toml (intl.toml). DO NOT EDIT.\n")
	b.WriteString("// The catalogs for intl.mjs's message: per catalog, its messages in key order (the index the generated\n// constructors pass).\n")
	b.WriteString("export default {\n")
	for i, id := range ids {
		fmt.Fprintf(&b, "  %q: [\n", id)
		for k, msg := range catalogs[id] {
			j, err := json.Marshal(msg)
			if err != nil {
				return err
			}
			b.WriteString("    " + string(j) + map[bool]string{true: ",\n", false: "\n"}[k < len(catalogs[id])-1])
		}
		b.WriteString("  ]" + map[bool]string{true: ",\n", false: "\n"}[i < len(ids)-1])
	}
	b.WriteString("};\n")
	return writeFile(path, []byte(b.String()))
}

func prefixComma(args []string) string {
	if len(args) == 0 {
		return ""
	}
	return ", " + strings.Join(args, ", ")
}

// GoName is the generated constructor for a key: "board.presence_label" → BoardPresenceLabel.
func GoName(key string) string {
	var b strings.Builder
	upper := true
	for _, r := range key {
		if r == '.' || r == '_' || r == '-' {
			upper = true
			continue
		}
		if upper {
			b.WriteRune(unicode.ToUpper(r))
			upper = false
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}

func paramName(arg string) string {
	n := GoName(arg)
	if n == "" {
		return "arg"
	}
	n = strings.ToLower(n[:1]) + n[1:]
	switch n {
	case "type", "func", "range", "map", "var", "default", "select", "case", "go", "string", "len":
		n += "_"
	}
	return n
}

// pseudoNodes pseudo-localizes text: accents on ASCII letters, 40% expansion, brackets around the message.
func pseudoNodes(nodes []node, top bool) []node {
	out := make([]node, len(nodes))
	for i, n := range nodes {
		if n.kind == kText {
			n.text = pseudoText(n.text)
		}
		if len(n.cases) > 0 {
			cases := make([]caseNode, len(n.cases))
			for k, c := range n.cases {
				cases[k] = caseNode{key: c.key, parts: pseudoNodes(c.parts, false)}
			}
			n.cases = cases
		}
		out[i] = n
	}
	if top {
		out = append([]node{{kind: kText, text: "⟦"}}, append(out, node{kind: kText, text: "⟧"})...)
	}
	return out
}

var accents = map[rune]rune{'a': 'á', 'b': 'ƀ', 'c': 'ç', 'd': 'ð', 'e': 'é', 'f': 'ƒ', 'g': 'ĝ', 'h': 'ĥ', 'i': 'í', 'j': 'ĵ', 'k': 'ķ', 'l': 'ļ', 'm': 'ɱ', 'n': 'ñ', 'o': 'ó', 'p': 'þ', 'q': 'ǫ', 'r': 'ŕ', 's': 'š', 't': 'ţ', 'u': 'ú', 'v': 'ṽ', 'w': 'ŵ', 'x': 'ẋ', 'y': 'ý', 'z': 'ž',
	'A': 'Å', 'B': 'Ɓ', 'C': 'Ç', 'D': 'Đ', 'E': 'É', 'F': 'Ƒ', 'G': 'Ĝ', 'H': 'Ĥ', 'I': 'Î', 'J': 'Ĵ', 'K': 'Ķ', 'L': 'Ļ', 'M': 'Ṁ', 'N': 'Ñ', 'O': 'Ö', 'P': 'Þ', 'Q': 'Ǫ', 'R': 'Ŕ', 'S': 'Š', 'T': 'Ţ', 'U': 'Û', 'V': 'Ṽ', 'W': 'Ŵ', 'X': 'Ẋ', 'Y': 'Ý', 'Z': 'Ž'}

func pseudoText(s string) string {
	var b strings.Builder
	letters := 0
	for _, r := range s {
		if a, ok := accents[r]; ok {
			b.WriteRune(a)
			letters++
		} else {
			b.WriteRune(r)
		}
	}
	for k := 0; k < letters*2/5; k++ {
		b.WriteRune('·')
	}
	return b.String()
}

func writeGo(path, src string) error {
	out, err := format.Source([]byte(src))
	if err != nil {
		os.WriteFile(path+".broken", []byte(src), 0o644)
		return fmt.Errorf("intl gen: %s: %w", path, err)
	}
	return writeFile(path, out)
}
