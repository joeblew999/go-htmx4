package catalog

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

// gsxuiT is a gsxui component writing its own text: i18n.T("Next slide").
var gsxuiT = regexp.MustCompile(`i18n\.T\(("(?:[^"\\]|\\.)*")\)`)

// GsxuiText is text a vendored gsxui component writes itself (i18n.T, whose English text is its id: the gsxui
// Internationalization guide), the first component file that writes it, and the catalogs' key for it: the English in
// snake case under [gsxui] ("Next slide" → gsxui.next_slide).
type GsxuiText struct {
	Text, File, Key string
}

// Gsxui is every text the components in intl.toml's gsxui directory write, sorted.
func (p *Project) Gsxui() ([]GsxuiText, error) {
	if p.Config.Gsxui == "" {
		return nil, nil
	}
	files, err := filepath.Glob(filepath.Join(p.Config.Root, p.Config.Gsxui, "*.gsx"))
	if err != nil {
		return nil, err
	}
	seen := map[string]bool{}
	var out []GsxuiText
	for _, f := range files {
		b, err := os.ReadFile(f)
		if err != nil {
			return nil, err
		}
		for _, m := range gsxuiT.FindAllSubmatch(b, -1) {
			text, err := strconv.Unquote(string(m[1]))
			if err != nil {
				return nil, fmt.Errorf("intl: %s: %s: %w", f, m[1], err)
			}
			if !seen[text] {
				seen[text] = true
				out = append(out, GsxuiText{Text: text, File: filepath.Join(p.Config.Gsxui, filepath.Base(f)), Key: "gsxui." + snake(text)})
			}
		}
	}
	slices.SortFunc(out, func(a, b GsxuiText) int { return strings.Compare(a.Text, b.Text) })
	return out, nil
}

// GsxuiProblems are the gsxui texts without a message, each naming the line to add to the source catalog.
func (p *Project) GsxuiProblems() ([]string, error) {
	texts, err := p.Gsxui()
	if err != nil {
		return nil, err
	}
	var out []string
	for _, t := range texts {
		switch m := p.Message(t.Key); {
		case m == nil:
			out = append(out, fmt.Sprintf("%s writes i18n.T(%q): add %s = %q to %s/%s.toml", t.File, t.Text, t.Key, literal(t.Text), p.Config.Catalogs, p.Config.Locales[0]))
		case len(m.Args) > 0:
			out = append(out, fmt.Sprintf("%s is i18n.T(%q), which has no arguments: its braces are gsxui's, quoted in ICU, %s = %q", t.Key, t.Text, t.Key, literal(t.Text)))
		}
	}
	return out, nil
}

// writeGsxui writes <gsxui>/i18n/intl_gen.go, T's renderer. A text without its message stops gen, naming the key to
// add: after gsxui add, mise run intl says what to translate.
func (p *Project) writeGsxui() error {
	texts, err := p.Gsxui()
	if err != nil {
		return err
	}
	dir := filepath.Join(p.Config.Root, p.Config.Gsxui)
	if _, err := os.Stat(filepath.Join(dir, "i18n")); err != nil {
		if len(texts) == 0 {
			return nil // no gsxui component vendored yet
		}
		return fmt.Errorf("intl: %s writes i18n.T, but there is no %s/i18n: gsxui add vendors it with the component", texts[0].File, p.Config.Gsxui)
	}
	if problems, err := p.GsxuiProblems(); err != nil {
		return err
	} else if len(problems) > 0 {
		return errors.New("intl: gsxui text without a message:\n  " + strings.Join(problems, "\n  "))
	}
	pkg, err := PackagePath(p.Config.CatalogDir())
	if err != nil {
		return err
	}
	name := filepath.Base(p.Config.CatalogDir())
	var b strings.Builder
	b.WriteString("// Code generated by go tool intl gen from " + name + "/*.toml [gsxui] (intl.toml). DO NOT EDIT.\n\npackage i18n\n\n")
	b.WriteString("import (\n\"context\"\n\n\"" + ImportPath + "\"\n\"" + pkg + "\"\n)\n\n")
	b.WriteString("// Translate is T's renderer (gsx.toml [renderers]): the text a gsxui component writes itself, in the request's\n// language, from the catalogs' [gsxui] messages.\n")
	b.WriteString("func Translate(ctx context.Context, m T) string {\nswitch m {\n")
	for _, t := range texts {
		fmt.Fprintf(&b, "case %q:\nreturn intl.Translate(ctx, %s.%s)\n", t.Text, name, GoName(t.Key))
	}
	b.WriteString("}\nreturn string(m)\n}\n")
	return writeGo(filepath.Join(dir, "i18n", "intl_gen.go"), b.String())
}

// snake is a key for English text: "Displays the mobile sidebar." → "displays_the_mobile_sidebar".
func snake(s string) string {
	var b strings.Builder
	gap := false
	for _, r := range strings.ToLower(s) {
		if r >= 'a' && r <= 'z' || r >= '0' && r <= '9' {
			if gap && b.Len() > 0 {
				b.WriteByte('_')
			}
			b.WriteRune(r)
			gap = false
		} else {
			gap = true
		}
	}
	return b.String()
}

// PackagePath is dir's Go import path, from the module path in the nearest go.mod at or above it.
func PackagePath(dir string) (string, error) {
	for root := dir; ; {
		b, err := os.ReadFile(filepath.Join(root, "go.mod"))
		if err == nil {
			for line := range strings.Lines(string(b)) {
				if mod, ok := strings.CutPrefix(strings.TrimSpace(line), "module "); ok {
					rel, err := filepath.Rel(root, dir)
					if err != nil {
						return "", err
					}
					return strings.TrimSuffix(strings.Trim(mod, `"`)+"/"+filepath.ToSlash(rel), "/."), nil
				}
			}
			return "", errors.New(root + "/go.mod has no module line")
		}
		parent := filepath.Dir(root)
		if parent == root {
			return "", errors.New("intl: no go.mod above " + dir)
		}
		root = parent
	}
}

// literal is gsxui's text as an ICU message that formats to exactly it: a placeholder gsxui's own script fills in
// ("Today, {date}") is quoted, "Today, '{date}'", since in ICU braces mark an argument.
func literal(text string) string {
	return strings.NewReplacer("{", "'{", "}", "}'").Replace(text)
}
