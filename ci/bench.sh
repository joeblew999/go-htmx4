#!/usr/bin/env bash
# CPU per request of the Worker on a local workerd, measured by charter's go tool workerbench (the operating
# system's count of workerd's CPU time over repeated requests; no Cloudflare account needed):
#
#   ci/bench.sh             the current build (mise run bench; CI runs it and adds the table to its summary)
#   ci/bench.sh variants    the current code built with each of charter's optimisations off in turn, written to
#                           docs/benchmarks.md (mise run bench:variants; ~3 min per build, cached after)
#
# BENCH_N and BENCH_RUNS set requests per kind and runs (defaults 60 and 3).
set -euo pipefail
cd "$(dirname "$0")/.."
reads=('GET /healthz' 'GET /de/' 'GET /board?topic=bench' 'GET /de/formats')
writes=('POST /board/add?topic=bench delta=1')
n=${BENCH_N:-60}
runs=${BENCH_RUNS:-3}
# Reads go flat out; writes are paced (-every) to stay under the app's write limit (60 per 10 s). Waiting costs
# no CPU, so pacing changes how long a run takes, never what it measures. With -json the two halves are one object.
measure() {
  go tool workerbench -n "$n" -runs "$runs" "$@" "${reads[@]}"
  go tool workerbench -n "$n" -runs "$runs" -every 170ms "$@" "${writes[@]}"
}
bench() {
  export n runs
  export -f measure
  if [[ " $* " == *" -json "* ]]; then
    ci/with-workerd.sh bench bash -c "$(declare -p reads writes); measure $(printf '%q ' "$@")" | sed -n '/^{/,$p' | jq -s '.[0] + {requests: (.[0].requests + .[1].requests)}'
  else
    ci/with-workerd.sh bench bash -c "$(declare -p reads writes); measure $(printf '%q ' "$@")"
  fi
}

if [ "${1:-}" != variants ] && [ "${1:-}" != render ]; then
  [ -e build/.prod ] || { echo "✗ no production build: mise run build"; exit 1; }
  bench -label "this build"
  exit 0
fi

# Each variant is the current code built with WORKERBUILD_FLAGS (ci/wasm-build.sh); the last is what ships.
names=("A runtime per request, TinyGo as it ships" "B A + TinyGo patched (tinygo#5800), 8 MB heap" "C runtimes reused, TinyGo as it ships" "D what ships: runtimes reused + TinyGo patched")
flags=("-reuse=false -patches=false -heap=0" "-reuse=false" "-patches=false" "")
# ci/bench.sh render DIR writes docs/benchmarks.md again from a run's results (DIR/N.json) without measuring.
if [ "$1" = render ]; then out=$2; else
out=build/bench
rm -rf "$out" && mkdir -p "$out"
for i in "${!names[@]}"; do
  echo "── ${names[$i]} (workerbuild ${flags[$i]:-defaults})"
  WORKER_COMPILER=tinygo WORKERBUILD_FLAGS="${flags[$i]}" ci/wasm-build.sh
  bench -label "${names[$i]}" -json >"$out/$i.json"
  jq -r '.requests[] | "  \(.request): \(.median*10|round/10) ms (runs \(.runs | map(.*10|round/10|tostring) | join(", ")))"' "$out/$i.json"
done
ci/wasm-build.sh >/dev/null # leave build/ as it ships
fi

{
  echo "# Benchmarks"
  echo
  echo "<!-- Generated by \`mise run bench:variants\` (ci/bench.sh): edit that, not this file. -->"
  echo
  echo "CPU per request of this Worker on a local workerd, in ms: the median of $runs runs of $n requests each, after warm requests,"
  echo "measured by charter's \`go tool workerbench\` from the operating system's count of workerd's CPU time. Each row is"
  echo "the same code built with \`go tool workerbuild\` and one or more of its optimisations off. Absolute numbers depend on the"
  echo "machine ($(jq -r .platform "$out/0.json"), $(date -u +%Y-%m-%d)); compare rows."
  echo
  printf '| Build |'; jq -r '.requests[] | " `\(.request)` |"' "$out/0.json" | tr -d '\n'; echo
  printf '|---|'; jq -r '.requests[] | "---|"' "$out/0.json" | tr -d '\n'; echo
  for i in "${!names[@]}"; do
    printf '| %s (`%s`) |' "${names[$i]}" "${flags[$i]:-defaults}"
    jq -r '.requests[] | " \(.median*10|round/10) |"' "$out/$i.json" | tr -d '\n'; echo
  done
  echo
  echo "Every run of every cell, to see how much a number moves:"
  echo
  for i in "${!names[@]}"; do
    echo "- ${names[$i]}: $(jq -r '[.requests[] | "\(.request) \(.runs | map(.*10|round/10|tostring) | join("/"))"] | join("; ")' "$out/$i.json")"
  done
} >docs/benchmarks.md
echo "✓ docs/benchmarks.md"
