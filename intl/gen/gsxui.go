package gen

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"

	"github.com/joeblew999/go-htmx4/intl/config"
)

// gsxuiT is a gsxui component writing its own text: i18n.T("Next slide").
var gsxuiT = regexp.MustCompile(`i18n\.T\(("(?:[^"\\]|\\.)*")\)`)

// writeGsxui writes the translator for the text gsxui components write themselves (i18n.T, whose English text is
// its id: the gsxui Internationalization guide) to <gsxui>/i18n/intl_gen.go. Each T the vendored components write is
// the catalogs' gsxui.<key>, the key being the English text in snake case ("Next slide" → gsxui.next_slide). A T
// without its message stops gen and names the key to add, so after gsxui add, mise run intl says what to translate.
func writeGsxui(c config.Config, msgs []*message) error {
	dir := filepath.Join(c.Root, c.Gsxui)
	files, err := filepath.Glob(filepath.Join(dir, "*.gsx"))
	if err != nil {
		return err
	}
	where := map[string]string{} // T text → the first component file writing it
	for _, f := range files {
		b, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		for _, m := range gsxuiT.FindAllSubmatch(b, -1) {
			text, err := strconv.Unquote(string(m[1]))
			if err != nil {
				return fmt.Errorf("intl gen: %s: %s: %w", f, m[1], err)
			}
			if _, seen := where[text]; !seen {
				where[text] = filepath.Base(f)
			}
		}
	}
	texts := make([]string, 0, len(where))
	for t := range where {
		texts = append(texts, t)
	}
	slices.Sort(texts)
	if _, err := os.Stat(filepath.Join(dir, "i18n")); err != nil {
		if len(texts) == 0 {
			return nil // no gsxui component vendored yet
		}
		return fmt.Errorf("intl gen: %s/%s writes i18n.T, but there is no %s/i18n: gsxui add vendors it with the component", c.Gsxui, where[texts[0]], c.Gsxui)
	}

	pkg, err := importPath(c.CatalogDir())
	if err != nil {
		return err
	}
	name := filepath.Base(c.CatalogDir())
	var b strings.Builder
	var missing []string
	b.WriteString("// Code generated by go tool intl gen from " + name + "/*.toml [gsxui] (intl.toml). DO NOT EDIT.\n\npackage i18n\n\n")
	b.WriteString("import (\n\"context\"\n\n\"" + ImportPath + "\"\n\"" + pkg + "\"\n)\n\n")
	b.WriteString("// Translate is T's renderer (gsx.toml [renderers]): the text a gsxui component writes itself, in the request's\n// language, from the catalogs' [gsxui] messages.\n")
	b.WriteString("func Translate(ctx context.Context, m T) string {\nswitch m {\n")
	for _, t := range texts {
		key := "gsxui." + snake(t)
		i := slices.IndexFunc(msgs, func(m *message) bool { return m.key == key })
		switch {
		case i < 0:
			missing = append(missing, fmt.Sprintf("%s/%s writes i18n.T(%q): add %s = %q to %s/%s.toml",
				c.Gsxui, where[t], t, key, t, c.Catalogs, c.Locales[0]))
			continue
		case len(msgs[i].parsed.order) > 0:
			return fmt.Errorf("intl gen: %s is i18n.T(%q), which has no arguments", key, t)
		}
		fmt.Fprintf(&b, "case %q:\nreturn intl.Translate(ctx, %s.%s())\n", t, name, goName(key))
	}
	if len(missing) > 0 {
		return errors.New("intl gen: gsxui text without a message:\n  " + strings.Join(missing, "\n  "))
	}
	b.WriteString("}\nreturn string(m)\n}\n")
	return writeGo(filepath.Join(dir, "i18n", "intl_gen.go"), b.String())
}

// snake is a key for English text: "Displays the mobile sidebar." → "displays_the_mobile_sidebar".
func snake(s string) string {
	var b strings.Builder
	gap := false
	for _, r := range strings.ToLower(s) {
		if r >= 'a' && r <= 'z' || r >= '0' && r <= '9' {
			if gap && b.Len() > 0 {
				b.WriteByte('_')
			}
			b.WriteRune(r)
			gap = false
		} else {
			gap = true
		}
	}
	return b.String()
}

// importPath is dir's Go import path, from the module path in the nearest go.mod above it.
func importPath(dir string) (string, error) {
	for root := dir; ; {
		b, err := os.ReadFile(filepath.Join(root, "go.mod"))
		if err == nil {
			for line := range strings.Lines(string(b)) {
				if mod, ok := strings.CutPrefix(strings.TrimSpace(line), "module "); ok {
					rel, err := filepath.Rel(root, dir)
					if err != nil {
						return "", err
					}
					return strings.TrimSuffix(strings.Trim(mod, `"`)+"/"+filepath.ToSlash(rel), "/."), nil
				}
			}
			return "", errors.New(root + "/go.mod has no module line")
		}
		parent := filepath.Dir(root)
		if parent == root {
			return "", errors.New("intl gen: no go.mod above " + dir)
		}
		root = parent
	}
}
